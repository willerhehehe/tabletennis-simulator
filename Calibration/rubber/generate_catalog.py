from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
rows=json.loads((ROOT/'results.json').read_text())['profiles']
meta=[('反胶·进攻板','andro Hexer Duro / Carbospeed / 2.1 mm'),('反胶·进攻板','andro Power 3 / Carbospeed / 1.8 mm'),('反胶·防守板','andro Hexer Duro / Defense Plus / 2.1 mm'),('反胶·防守板','andro Power 3 / Defense Plus / 1.8 mm'),('长胶·1.2 mm','Tibhar Grass D.TecS / Allplay Senso V1 / 1.2 mm'),('长胶·OX','Tibhar Grass D.TecS / Allplay Senso V1 / OX'),('中颗粒','Dr. Neubauer Diamant / Allplay Senso V1 / 1.2 mm'),('正胶','andro Blowfish / Allplay Senso V1 / 2.0 mm'),('反胶·全面板','andro Hexer Duro / Allplay Senso V1 / 2.1 mm'),('防弧','Dr. Neubauer A-B-S II soft / Allplay Senso V1 / 2.1 mm')]
lines=[]
for r,(name,equipment) in zip(rows,meta):
 vals=[r[k] for k in ['e','mu','beta']]+r['normal_speed_range_m_s']+r['surface_slip_range_m_s']+[r['fitted_test']['velocity_mae_m_s'],r['fitted_test']['spin_mae_rps'],r['velocity_improvement_pct'],r['spin_improvement_pct']]
 lines.append('            new RubberCalibration('+str(r['id'])+', '+json.dumps(name,ensure_ascii=False)+', '+json.dumps(equipment)+', '+', '.join(format(x,'.17g') for x in vals)+', '+str(r['test_count'])+', '+str(r['id'] in [5,6]).lower()+'),')
code='''// Generated by Calibration/rubber/generate_catalog.py from training-only fits.
using System;
using System.Collections.Generic;
namespace TableTennis
{
    public sealed class RubberCalibration
    {
        public readonly int Id, TestCount;
        public readonly string Name, Equipment;
        public readonly double Restitution, Friction, Tangent, NormalMin, NormalMax, SlipMin, SlipMax;
        public readonly double VelocityError, SpinErrorRps, VelocityImprovement, SpinImprovement;
        public readonly bool Limited;
        public RubberCalibration(int id, string name, string equipment, double e, double mu, double beta,
            double normalMin, double normalMax, double slipMin, double slipMax, double velocityError, double spinError,
            double velocityImprovement, double spinImprovement, int testCount, bool limited)
        {
            Id=id; Name=name; Equipment=equipment; Restitution=e; Friction=mu; Tangent=beta;
            NormalMin=normalMin; NormalMax=normalMax; SlipMin=slipMin; SlipMax=slipMax;
            VelocityError=velocityError; SpinErrorRps=spinError; VelocityImprovement=velocityImprovement;
            SpinImprovement=spinImprovement; TestCount=testCount; Limited=limited;
        }
        public bool Matches(double e, double mu, double beta) =>
            Math.Abs(e-Restitution)<1e-6 && Math.Abs(mu-Friction)<1e-6 && Math.Abs(beta-Tangent)<1e-6;
    }
    public static class RubberCalibrations
    {
        public const string Source = "https://github.com/gossardt/tt_rackets";
        public const string SourceCommit = "159c6f040dd7832570b537b3b5fd00a97fc28c15";
        public static readonly IReadOnlyList<RubberCalibration> All = Array.AsReadOnly(new[] {
'''+ '\n'.join(lines)+'''
        });
        public static string Identify(double e, double mu, double beta)
        {
            foreach(var p in All) if(p.Matches(e,mu,beta)) return "tt_rackets-R"+p.Id.ToString("00")+"-constant-v1";
            return "custom-or-unfitted";
        }
    }
}
'''
(ROOT.parents[1]/'Assets/Scripts/Core/RubberCalibrations.cs').write_text(code)
